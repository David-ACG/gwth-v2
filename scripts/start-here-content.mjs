#!/usr/bin/env node
/**
 * Snapshot lesson zero (Start Here) into the site for /start-here.
 *
 * /start-here serves the free lesson to anyone who has confirmed an email
 * address, without an account, so it cannot read the lesson from the course
 * tables (lesson zero is not published there, and the course viewer needs a
 * signed-in learner). The page renders this snapshot instead.
 *
 * It copies ONLY what David has approved, plus the project exactly as it
 * stands (the project was rebuilt around Handy and waits for his re-approval;
 * the hand-over says so). Re-run it after he approves a new version in the
 * Words check, then commit the generated file:
 *
 *   node scripts/start-here-content.mjs [lesson folder]
 *
 * Writes src/lib/start-here/content.generated.ts. Bead gwth-launch-xw6s.
 */
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const DEFAULT_DIR =
  "/home/david/gwth-dashboard/generated_lessons/m1_l00_start_here_the_tips_we_wish_we_d_had_when_we_started"
const dir = process.argv[2] ?? DEFAULT_DIR

// lesson.md is the text David approved in the Words check on 2026-10-09. A
// lesson.candidate.md beside it is a later rewrite he has NOT approved, so it
// is never read here.
const lesson = readFileSync(join(dir, "content", "lesson.md"), "utf8")
const project = readFileSync(join(dir, "content", "project.candidate.md"), "utf8")
const sha = (s) => createHash("sha256").update(s).digest("hex")

const out = `/**
 * GENERATED by scripts/start-here-content.mjs. Do not edit by hand: change the
 * lesson in the Words check, then re-run the script.
 *
 * Source: ${dir}
 */

export const START_HERE_SOURCE = {
  lessonFile: "content/lesson.md",
  lessonSha256: "${sha(lesson)}",
  lessonState: "approved by David in the Words check, 2026-10-09",
  projectFile: "content/project.candidate.md",
  projectSha256: "${sha(project)}",
  projectState: "rebuilt around Handy, waiting for David's re-approval",
} as const

export const START_HERE_LESSON_MD: string = ${JSON.stringify(lesson)}

export const START_HERE_PROJECT_MD: string = ${JSON.stringify(project)}
`

const target = new URL("../src/lib/start-here/content.generated.ts", import.meta.url)
writeFileSync(target, out)
console.log(`wrote ${target.pathname} (lesson ${sha(lesson).slice(0, 12)}, project ${sha(project).slice(0, 12)})`)
